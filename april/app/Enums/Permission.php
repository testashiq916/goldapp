    public static function matchPermissionForRequest(Request $request): ?string
    {
        $path = trim($request->path(), '/');
        $normalizedPath = preg_replace('#^api/#i', '', $path) ?: $path;

        if (preg_match('#^customer(?:/.*)?$#i', $path) === 1 || preg_match('#^customer(?:/.*)?$#i', $normalizedPath) === 1) {
            $type = strtoupper(trim((string) $request->query('type', 'C')));
            if ($type === 'F') {
                return 'MDI_STAFF_MASTER';
            }
        }

        return self::matchPermissionForPath($path);
    }

    public static function matchPermissionForPath(string $path): ?string
    {
        $path = trim($path, '/');
        $normalizedPath = preg_replace('#^api/#i', '', $path) ?: $path;

        foreach (self::routePatterns() as $pattern => $permission) {
            $regex = '#^' . str_replace('\*', '.*', preg_quote(trim($pattern, '/'), '#')) . '$#i';
            if (preg_match($regex, $path) === 1 || preg_match($regex, $normalizedPath) === 1) {
                return $permission;
            }
        }

        return null;
    }

