    public static function groupedLabels(): array
    {
        $all = self::all();
        $grouped = [];

        foreach (self::grouped() as $group => $keys) {
            $grouped[$group] = [];
            foreach ($keys as $key) {
                $grouped[$group][$key] = $all[$key] ?? $key;
            }
        }

        return $grouped;
    }

